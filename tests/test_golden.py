"""Golden tests: the shipped profiles reproduce the previous installer's output (QLT-3).

``fixtures/baseline/v0-installer-output.json`` records what the hand-written installer produced
before profiles existed; ``fixtures/golden/sources`` are the same sources in the neutral format.
Every difference must be listed in ``INTENDED_DIFFERENCES`` with its reason.
"""

import json
import re
from pathlib import Path

from lantoki.compiler import Artifact, CompileContext, compile_scope
from lantoki.frontmatter import parse
from lantoki.profiles import load_profiles
from lantoki.sources import Scope, load_sources
from tests.conftest import FIXTURES, REAL_PROVIDERS_DIR


HOME = Path("/HOME")
REPO = Path("/REPO")
SOURCES = FIXTURES / "golden" / "sources"
BASELINE = json.loads((FIXTURES / "baseline" / "v0-installer-output.json").read_text(encoding="utf-8"))
OLD_TO_NEW_LAYOUT = {"user-level/skills/": "user/skills/", "project-level/project-skills/": "project/skills/"}
_MARKER = re.compile(r"<!-- Generated by lantoki from [^>]*-->\n\n")

_ADDED_DESCRIPTION = "placeholder source had no description; the neutral format requires one (SRC-3)"
_COPILOT_NAME = "Copilot 'name' is now the source title; it was the file name, which Copilot already uses"
_COPILOT_AGENT = (
    "neutral tool round-trip: agent/runSubagent -> agent, web/githubRepo has no neutral equivalent, "
    "duplicate todo removed; Copilot defaults user-invocable/disable-model-invocation dropped (SRC-5)"
)
INTENDED_DIFFERENCES = {
    "{home}/.claude/rules/linux-dev.md": _ADDED_DESCRIPTION,
    "{home}/.config/Code/User/instructions/linux-dev.instructions.md": _ADDED_DESCRIPTION,
    "{repo}/.claude/skills/generate-docs/SKILL.md": _ADDED_DESCRIPTION,
    "{repo}/.github/prompts/generate-docs.prompt.md": _ADDED_DESCRIPTION,
    "{home}/.config/Code/User/instructions/dependencies.instructions.md": _COPILOT_NAME,
    "{home}/.config/Code/User/instructions/general.instructions.md": _COPILOT_NAME,
    "{home}/.config/Code/User/prompts/k8s-namespace-root-cause.prompt.md": (
        "Copilot argument placeholder is the documented ${input:arguments} form (SRC-4)"
    ),
    "{home}/.copilot/agents/bash2python.agent.md": _COPILOT_AGENT,
    "{home}/.copilot/agents/performance-tests-creator.agent.md": _COPILOT_AGENT,
    "{home}/.copilot/agents/security-bandit-remediator.agent.md": _COPILOT_AGENT,
    "{repo}/AGENTS.md": "one neutral repo-instructions source replaces two placeholder files (SRC-8)",
    "{repo}/.github/copilot-instructions.md": "Copilot reads AGENTS.md; a second always-on file would duplicate it",
    "{repo}/.vscode/mcp.json": "no project MCP servers are declared, so no empty config is installed",
}


def _compiled() -> dict[str, Artifact]:
    profiles = load_profiles(REAL_PROVIDERS_DIR)
    sources = load_sources(SOURCES)
    artifacts: dict[str, Artifact] = {}
    for scope, repo in ((Scope.USER, None), (Scope.PROJECT, REPO)):
        context = CompileContext(scope, HOME, SOURCES, repo)
        artifacts.update(
            {artifact.installed_path: artifact for artifact in compile_scope(sources, profiles, context).artifacts}
        )
    return artifacts


def _equivalent_markdown(old: str, new: str) -> bool:
    old_document, new_document = parse(old), parse(new)
    same_body = _MARKER.sub("", old_document.body).strip() == _MARKER.sub("", new_document.body).strip()
    return old_document.front_matter == new_document.front_matter and same_body


def _matches(expected: dict[str, str], artifact: Artifact) -> bool:
    if artifact.content is None:
        old_link = expected["link"]
        for old, new in OLD_TO_NEW_LAYOUT.items():
            old_link = old_link.replace(old, new)
        return artifact.link_source == SOURCES / old_link
    if artifact.target.endswith(".json"):
        return json.loads(expected["content"]) == json.loads(artifact.content)
    return _equivalent_markdown(expected["content"], artifact.content)


def test_given_golden_sources_when_compiled_with_shipped_profiles_then_only_intended_differences_remain() -> None:
    compiled = _compiled()

    differing = set()
    for key, expected in BASELINE.items():
        artifact = compiled.get(key.replace("{home}", str(HOME)).replace("{repo}", str(REPO)))
        if artifact is None or not _matches(expected, artifact):
            differing.add(key)

    assert differing == set(INTENDED_DIFFERENCES)


def test_given_golden_sources_when_compiled_then_new_targets_are_only_the_claude_mcp_registration() -> None:
    old_targets = {key.replace("{home}", str(HOME)).replace("{repo}", str(REPO)) for key in BASELINE}

    new_targets = set(_compiled()) - old_targets

    assert new_targets == {"command:claude-code:user:python-verification-gate"}
