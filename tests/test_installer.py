def test_given_ask_answers_when_syncing_repo_then_selection_is_remembered(
    acme_workspace: Workspace,
    repo: Path,
    home: Path,
) -> None:
    asked: list[str] = []

    def ask(source: object) -> bool:
        asked.append(source.key)  # type: ignore[attr-defined]
        return source.key in {"instruction:python", "mcp:db"}  # type: ignore[attr-defined]

    first = run_scope(acme_workspace, Scope.PROJECT, repo, ask=ask, apply=True)
    second = run_scope(acme_workspace, Scope.PROJECT, repo, ask=ask, apply=True)

    manifest = json.loads(next((home / ".local" / "state" / "lantoki" / "manifests").glob("repo-*.json")).read_text())
    assert first.selected == ["instruction:python", "mcp:db"]
    assert second.selected == first.selected
    assert len(asked) == len(set(asked)) == 6
    assert (repo / ".acme" / "rules" / "python.md").is_file()
    assert not (repo / ".acme" / "rules" / "airflow.md").exists()
    assert manifest["selection"] == ["instruction:python", "mcp:db"]


