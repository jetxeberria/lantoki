def _actions(outcome: object) -> dict[str, Action]:
    return {step.target: step.action for step in outcome.plan.steps}  # type: ignore[attr-defined]


def _install_cli(home: Path, version: str = "1.2.3") -> Path:
    cli = home / "acme" / version / "acme"
    cli.parent.mkdir(parents=True)
    cli.write_text("#!/bin/sh\n", encoding="utf-8")
    cli.chmod(0o755)
    return cli


def test_given_empty_home_when_syncing_user_then_targets_link_to_store_and_sources(
    acme_workspace: Workspace,
    home: Path,
    sources_root: Path,
) -> None:
    outcome = run_scope(acme_workspace, Scope.USER, apply=True)

    rule = home / ".acme" / "rules" / "general.md"
    skill = home / ".acme" / "skills" / "demo"
    store = home / ".local" / "share" / "lantoki" / "compiled" / "user"
    assert outcome.ok
    assert rule.is_symlink()
    assert rule.resolve().is_relative_to(store)
    assert "Be kind." in rule.read_text(encoding="utf-8")
    assert skill.resolve() == sources_root / "user" / "skills" / "demo"
    assert (home / ".local" / "state" / "lantoki" / "manifests" / "user.json").is_file()


