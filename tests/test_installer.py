@pytest.mark.parametrize("earlier_install", ["generated_file", "symlink_into_project"])
def test_given_earlier_lantoki_install_when_syncing_then_it_is_adopted(
    acme_workspace: Workspace,
    home: Path,
    earlier_install: str,
) -> None:
    rule = home / ".acme" / "rules" / "general.md"
    rule.parent.mkdir(parents=True)
    if earlier_install == "generated_file":
        rule.write_text(
            "<!-- Generated by lantoki from old.md. Edit the source, not this file. -->\n", encoding="utf-8"
        )
    else:
        rule.symlink_to(acme_workspace.settings.project_root / "src" / "lantoki" / "gone" / "general.md")

    outcome = run_scope(acme_workspace, Scope.USER, apply=True)

    assert _actions(outcome)[str(rule)] is Action.ADOPT
    assert rule.is_symlink()
    assert "Be kind." in rule.read_text(encoding="utf-8")


