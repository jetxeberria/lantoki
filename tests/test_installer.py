def test_given_file_installed_inside_a_real_folder_when_profile_moves_to_file_then_folder_becomes_the_link(
    acme_env: Path,
    home: Path,
    tmp_path: Path,
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    del acme_env
    providers = tmp_path / "providers"
    providers.mkdir()
    profile = (FAKE_PROVIDERS_DIR / "acme.toml").read_text(encoding="utf-8")
    old_layout = profile.replace(
        'target = "{home}/.acme/commands/{name}"\nfile = "COMMAND.md"\n',
        'target = "{home}/.acme/commands/{name}/COMMAND.md"\n',
    )
    assert tomllib.loads(old_layout) != tomllib.loads(profile)
    (providers / "acme.toml").write_text(old_layout, encoding="utf-8")
    monkeypatch.setenv("LANTOKI_PROVIDERS_DIR", str(providers))
    run_scope(Workspace.load(load_settings()), Scope.USER, apply=True)
    command = home / ".acme" / "commands" / "review"
    assert not command.is_symlink()
    assert (command / "COMMAND.md").is_symlink()

    shutil.copy(FAKE_PROVIDERS_DIR / "acme.toml", providers / "acme.toml")
    outcome = run_scope(Workspace.load(load_settings()), Scope.USER, apply=True)
    again = run_scope(Workspace.load(load_settings()), Scope.USER, apply=True)

    actions = _actions(outcome)
    assert outcome.ok
    assert actions[str(command)] is Action.ADOPT
    assert actions[str(command / "COMMAND.md")] is Action.PRUNE
    assert command.is_symlink()
    assert "Review %ARGS% now." in (command / "COMMAND.md").read_text(encoding="utf-8")
    assert _actions(again)[str(command)] is Action.UNCHANGED
