def test_given_versioned_cli_when_syncing_user_then_newest_cli_registers_the_server_once(
    acme_workspace: Workspace,
    home: Path,
) -> None:
    _install_cli(home, "1.9.0")
    newest = _install_cli(home, "1.10.0")
    runner = FakeRunner()

    run_scope(acme_workspace, Scope.USER, apply=True, run_command=runner)
    second = run_scope(acme_workspace, Scope.USER, apply=True, run_command=runner)

    assert len(runner.calls) == 1
    assert runner.calls[0][:3] == [str(newest), "add", "gate"]
    assert _actions(second)["command:acme:user:gate"] is Action.UNCHANGED


