"""Read and write markdown files with YAML front matter."""

from __future__ import annotations

import re
from dataclasses import dataclass, field
from typing import TYPE_CHECKING, Any

import yaml


if TYPE_CHECKING:
    from collections.abc import Mapping


GENERATED_MARKER = "<!-- Generated by lantoki from {source}. Edit the source, not this file. -->"
GENERATED_MARKER_PREFIX = "<!-- Generated by lantoki from "

_FRONT_MATTER_RE = re.compile(r"\A---\s*\n(?P<front>.*?)\n---\s*\n?(?P<body>.*)\Z", re.DOTALL)


@dataclass(frozen=True)
class MarkdownDocument:
    """A markdown file split into its YAML front matter and body."""

    front_matter: dict[str, Any] = field(default_factory=dict)
    body: str = ""


def parse(text: str) -> MarkdownDocument:
    """Split markdown text into front matter and body; text without front matter is all body.

    Raises:
        TypeError: The front matter is valid YAML but not a mapping.
    """
    match = _FRONT_MATTER_RE.match(text)
    if match is None:
        return MarkdownDocument(front_matter={}, body=text)

    front_matter = yaml.safe_load(match["front"]) or {}
    if not isinstance(front_matter, dict):
        msg = "Front matter must be a YAML mapping"
        raise TypeError(msg)
    return MarkdownDocument(front_matter=front_matter, body=match["body"])


def render(front_matter: Mapping[str, Any], body: str, source_name: str | None = None) -> str:
    """Render front matter, an optional generated-file marker and the body as markdown."""
    parts: list[str] = []
    if front_matter:
        front_text = yaml.safe_dump(dict(front_matter), sort_keys=False, allow_unicode=True, width=1000)
        parts.append(f"---\n{front_text}---\n")
    if source_name is not None:
        parts.append(GENERATED_MARKER.format(source=source_name) + "\n\n")
    parts.append(body.lstrip("\n"))
    return "".join(parts)


def is_generated(text: str) -> bool:
    """Return True when text carries lantoki's generated-file marker."""
    return GENERATED_MARKER_PREFIX in text
